// Writes src/templates/registry.generated.ts from the template folders.
// Runs before `dev`, `build`, `test` and `typecheck`, so adding a template is
// adding a folder: src/templates/<id>/ with meta.ts, Template.tsx and demo.ts.
// Folders starting with "_" (like _kit) are skipped.

import fs from "node:fs";
import path from "node:path";

const DIR = path.resolve(import.meta.dirname, "..", "src", "templates");
const OUT = path.join(DIR, "registry.generated.ts");
const REQUIRED = ["meta.ts", "Template.tsx", "demo.ts"];

const ids = fs
  .readdirSync(DIR, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith("_") && !d.name.startsWith("."))
  .map((d) => d.name)
  .filter((id) => {
    const missing = REQUIRED.filter((f) => !fs.existsSync(path.join(DIR, id, f)));
    if (missing.length) console.warn(`templates: skipping "${id}" (missing ${missing.join(", ")})`);
    return missing.length === 0;
  })
  .sort();

for (const id of ids) {
  if (!/^[a-z][a-z0-9-]*$/.test(id)) throw new Error(`templates: folder name "${id}" must be lowercase letters, digits and dashes`);
}

const ident = (id) => id.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());
const source = `// Generated by scripts/build-template-registry.mjs. Do not edit; add a folder instead.
import type { ComponentType } from "react";
import type { TemplateDemo, TemplateMeta, TemplateProps } from "./_kit/types";
${ids.map((id) => `import ${ident(id)}Meta from "./${id}/meta";\nimport ${ident(id)}Demo from "./${id}/demo";`).join("\n")}

export const TEMPLATE_IDS = [${ids.map((id) => JSON.stringify(id)).join(", ")}] as const;

export const TEMPLATE_METAS: Record<string, TemplateMeta> = {
${ids.map((id) => `  ${JSON.stringify(id)}: ${ident(id)}Meta,`).join("\n")}
};

export const TEMPLATE_DEMOS: Record<string, TemplateDemo> = {
${ids.map((id) => `  ${JSON.stringify(id)}: ${ident(id)}Demo,`).join("\n")}
};

/** Loaded on demand so a page only pulls in the fonts and CSS of the template it shows. */
export const TEMPLATE_LOADERS: Record<string, () => Promise<{ default: ComponentType<TemplateProps> }>> = {
${ids.map((id) => `  ${JSON.stringify(id)}: () => import("./${id}/Template"),`).join("\n")}
};
`;

const previous = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
if (previous !== source) {
  fs.writeFileSync(OUT, source);
  console.log(`templates: registered ${ids.join(", ") || "none"}`);
}
